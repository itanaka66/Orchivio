"""A typed Python client for the data API of an application (docs/CLIENTS.md).

Generated from the same OpenAPI document as the TypeScript client: a single standard-library file (``urllib`` only, Python 3.8+) with
``TypedDict`` types per entity, create/update inputs, typed list parameters, one method per permitted operation and per runnable flow,
a typed error, and an injectable transport for tests. Deterministic for a given model; the header carries the model hash.
"""

from __future__ import annotations

import keyword
import re
from typing import Any

from orchivio.model import AppModel, model_hash

from .openapi import build_openapi
from .typescript import _referenced

_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _lit(value: Any) -> str:
    if value is None:
        return "None"
    if isinstance(value, bool):
        return "True" if value else "False"
    if isinstance(value, (int, float)):
        return repr(value)
    return repr(str(value))


def py_type(schema: dict[str, Any]) -> str:
    """The Python type annotation of a JSON-Schema fragment as produced by ``build_openapi``."""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        values = [v for v in schema["enum"] if v is not None]
        lit = f"Literal[{', '.join(_lit(v) for v in values)}]" if values else "Any"
        return f"Optional[{lit}]" if None in schema["enum"] else lit
    t = schema.get("type")
    if isinstance(t, list):
        parts = sorted({py_type({**schema, "type": x}) for x in t}, key=lambda s: (s == "None", s))
        non_null = [p for p in parts if p != "None"]
        if len(parts) == len(non_null):
            return f"Union[{', '.join(parts)}]" if len(parts) > 1 else parts[0]
        return f"Optional[{non_null[0]}]" if len(non_null) == 1 else f"Optional[Union[{', '.join(non_null)}]]"
    mapping = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}
    if t in mapping:
        return mapping[t]
    if t == "array":
        return f"List[{py_type(schema.get('items', {}))}]"
    if t == "object":
        return "Dict[str, Any]"
    return "Any"


def _typed_dict(name: str, schema: dict[str, Any], *, force_optional: bool = False) -> str:
    """``TypedDict`` definitions for an object schema. Required and optional keys are separate classes (``NotRequired`` needs 3.11)."""
    props = schema.get("properties", {})
    req = set(schema.get("required", [])) if not force_optional else set()
    required = {k: py_type(p) for k, p in props.items() if k in req}
    optional = {k: py_type(p) for k, p in props.items() if k not in req}
    out: list[str] = []
    bases: list[str] = []
    if required:
        out.append(f"_{name}Required = TypedDict('_{name}Required', {{{', '.join(f'{k!r}: {v}' for k, v in required.items())}}})")
        bases.append(f"_{name}Required")
    if optional or not required:
        out.append(f"_{name}Optional = TypedDict('_{name}Optional', {{{', '.join(f'{k!r}: {v}' for k, v in optional.items())}}}, total=False)")
        bases.append(f"_{name}Optional")
    doc = [f"#   {k}: " + ", ".join(b for b in _notes(p)) for k, p in props.items() if _notes(p)]
    head = ([f"# {name}: field notes"] + doc) if doc else []
    return "\n".join([*head, *out, f"class {name}({', '.join(bases)}):", "    pass", ""])


def _notes(p: dict[str, Any]) -> list[str]:
    notes = []
    if p.get("readOnly"):
        notes.append("read-only")
    if p.get("format") in ("uuid", "date", "date-time"):
        notes.append(str(p["format"]))
    if p.get("maxLength"):
        notes.append(f"max {p['maxLength']} characters")
    if "minimum" in p:
        notes.append(f"min {p['minimum']}")
    if "maximum" in p:
        notes.append(f"max {p['maximum']}")
    if p.get("x-orchivio-computed"):
        notes.append(f"computed ({p['x-orchivio-computed']})")
    return notes


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s).lower()
    return s + "_" if keyword.iskeyword(s) or s in {"list", "dict", "str", "int", "type"} and False else (s + "_" if keyword.iskeyword(s) else s)


def build_python_client(model: AppModel) -> str:
    doc = build_openapi(model)
    schemas: dict[str, Any] = doc["components"]["schemas"]
    used = _referenced(doc["paths"], schemas)
    out = [
        f"# Generated by Orchivio from the model of \"{model.application.key}\" ({model_hash(model)}). Do not edit; regenerate it.\n"
        "# Only operations that at least one role may perform are included. Which roles may do what is up to the server.\n",
        '"""Typed client for the data API of this application (standard library only, Python 3.8+)."""\n',
        "import json",
        "import urllib.error",
        "import urllib.parse",
        "import urllib.request",
        "from typing import Any, Callable, Dict, List, Literal, Optional, TypedDict, Union\n",
        "class OrchivioApiError(Exception):",
        '    """The server answered with an error; ``code``, ``message`` and ``details`` come from its error envelope."""\n',
        "    def __init__(self, status: int, code: str, message: str, details: Any = None) -> None:",
        "        super().__init__(f'{code}: {message}')",
        "        self.status, self.code, self.message, self.details = status, code, message, details\n",
    ]
    for name, schema in schemas.items():
        props = schema.get("properties", {})
        if name not in used or name == "Error":
            continue
        if {"items", "total", "limit", "offset"} <= set(props):
            out.append(_typed_dict(name, {**schema, "properties": {**props, "items": {"type": "array", "items": {"$ref": props["items"]["items"]["$ref"]}}}}))
            continue
        out.append(_typed_dict(name, schema))

    entities: dict[str, dict[str, Any]] = {}
    for path, ops in doc["paths"].items():
        if path.startswith("/data/"):
            for verb, op in ops.items():
                entities.setdefault(path.split("/")[2], {})[op["operationId"].split("_", 1)[0]] = (path, verb, op)

    classes, attrs = [], []
    for ops in entities.values():
        tag = next(iter(ops.values()))[2]["tags"][0]
        first = ops["read"] if "read" in ops else ops["list"]
        entity_t = py_type(first[2]["responses"]["200"]["content"]["application/json"]["schema"])
        entity_t = entity_t if "read" in ops else entity_t.removesuffix("Page")
        cls = f"_{entity_t}Api"
        lines = [f"class {cls}:", f'    """{tag}"""\n', "    def __init__(self, client: 'OrchivioDataClient') -> None:", "        self._c = client\n"]
        if "list" in ops:
            params = {p["name"]: p for p in ops["list"][2].get("parameters", []) if "name" in p}
            order = py_type(params["order_by"]["schema"]) if "order_by" in params else "str"
            filt = {n[2:]: p["schema"] for n, p in params.items() if n.startswith("f.")}
            fname = f"{entity_t}Filter"
            out.append(f"{fname} = TypedDict('{fname}', {{{', '.join(f'{k!r}: {py_type(v)}' for k, v in filt.items())}}}, total=False)\n")
            lines += [f"    def list(self, *, limit: Optional[int] = None, offset: Optional[int] = None, order_by: Optional[{order}] = None,",
                      f"             desc: Optional[bool] = None, filter: Optional[{fname}] = None) -> {entity_t}Page:",
                      '        """Equality filters apply to stored fields."""',
                      "        query: Dict[str, str] = {}",
                      "        if limit is not None:\n            query['limit'] = str(limit)",
                      "        if offset is not None:\n            query['offset'] = str(offset)",
                      "        if order_by:\n            query['order_by'] = order_by",
                      "        if desc:\n            query['desc'] = 'true'",
                      "        for key, value in (filter or {}).items():",
                      "            if value is not None:\n                query['f.' + key] = str(value)",
                      f"        return self._c._request('GET', {ops['list'][0]!r}, query=query)\n",
                      f"    def list_all(self, *, order_by: Optional[{order}] = None,",
                      f"                 desc: Optional[bool] = None, filter: Optional[{fname}] = None, limit: int = 100) -> List[{entity_t}]:",
                      '        """Fetch all pages and return a flat list. Use limit to control page size."""',
                      "        all_items, offset = [], 0",
                      "        while True:",
                      "            page = self.list(limit=limit, offset=offset, order_by=order_by, desc=desc, filter=filter)",
                      "            all_items.extend(page['items'])",
                      "            if not page['items'] or len(all_items) >= page['total']:",
                      "                break",
                      "            offset += len(page['items'])",
                      "        return all_items\n",
                      f"    def pages(self, *, order_by: Optional[{order}] = None,",
                      f"              desc: Optional[bool] = None, filter: Optional[{fname}] = None, limit: int = 100):",
                      f'        """Yield one {entity_t}Page at a time."""',
                      "        offset = 0",
                      "        while True:",
                      "            page = self.list(limit=limit, offset=offset, order_by=order_by, desc=desc, filter=filter)",
                      "            yield page",
                      "            if not page['items'] or offset + len(page['items']) >= page['total']:",
                      "                break",
                      "            offset += len(page['items'])\n"]
        if "create" in ops:
            body = py_type(ops["create"][2]["requestBody"]["content"]["application/json"]["schema"])
            lines += [f"    def create(self, body: {body}) -> {entity_t}:", f"        return self._c._request('POST', {ops['create'][0]!r}, body=body)\n"]
        if "read" in ops:
            lines += [f"    def get(self, id: str) -> {entity_t}:", f"        return self._c._request('GET', {ops['read'][0].replace('{id}', '')!r} + urllib.parse.quote(id, safe=''))\n"]
        if "update" in ops:
            body = py_type(ops["update"][2]["requestBody"]["content"]["application/json"]["schema"])
            lines += [f"    def update(self, id: str, patch: {body}) -> {entity_t}:",
                      f"        return self._c._request('PATCH', {ops['update'][0].replace('{id}', '')!r} + urllib.parse.quote(id, safe=''), body=patch)\n"]
        if "delete" in ops:
            lines += ["    def delete(self, id: str) -> None:", f"        self._c._request('DELETE', {ops['delete'][0].replace('{id}', '')!r} + urllib.parse.quote(id, safe=''))\n"]
        classes.append("\n".join(lines))
        attrs.append((snake(entity_t), cls))

    flow_paths = {p: ops["post"] for p, ops in doc["paths"].items() if p.startswith("/flows/")}
    if flow_paths:
        keys = [p.split("/")[2].split(".", 1)[1] for p in flow_paths]
        lines = ["class _FlowsApi:", '    """Server flows the caller\'s roles may run directly."""\n', "    def __init__(self, client: 'OrchivioDataClient') -> None:", "        self._c = client\n"]
        for path, op in flow_paths.items():
            module, key = path.split("/")[2].split(".", 1)
            args = py_type(op["requestBody"]["content"]["application/json"]["schema"]["properties"]["args"])
            member = snake(key) if keys.count(key) == 1 else snake(f"{module}_{key}")
            default = "" if op["requestBody"].get("required") else " = None"
            ann = args if not default else f"Optional[{args}]"
            lines += [f"    def {member}(self, args: {ann}{default}) -> FlowRunResult:",
                      f'        """{op["summary"]} (roles: {", ".join(op["x-orchivio-roles"])})"""',
                      f"        return self._c._request('POST', {path!r}, body={{'args': args" + (" or {}" if default else "") + "})\n"]
        classes.append("\n".join(lines))
        attrs.append(("flows" if "flows" not in {a for a, _ in attrs} else "flow_runs", "_FlowsApi"))

    out += classes
    out.append("\n".join([
        "class OrchivioDataClient:",
        '    """``OrchivioDataClient(base_url, headers=lambda: {...})``. ``opener(request, timeout)`` replaces ``urllib.request.urlopen`` (tests, proxies)."""\n',
        "    def __init__(self, base_url: str, *, headers: Optional[Callable[[], Dict[str, str]]] = None, timeout: float = 30.0,",
        "                 opener: Optional[Callable[..., Any]] = None) -> None:",
        "        self._base = base_url.rstrip('/')",
        "        self._headers, self._timeout, self._opener = headers, timeout, opener or urllib.request.urlopen",
        *[f"        self.{a} = {c}(self)" for a, c in attrs],
        "",
        "    def _request(self, method: str, path: str, *, query: Optional[Dict[str, str]] = None, body: Any = None) -> Any:",
        "        url = self._base + path + ('?' + urllib.parse.urlencode(query) if query else '')",
        "        headers = {'Accept': 'application/json'}",
        "        headers.update(self._headers() if self._headers else {})",
        "        data = None",
        "        if body is not None:",
        "            data = json.dumps(body).encode('utf-8')",
        "            headers['Content-Type'] = 'application/json'",
        "        request = urllib.request.Request(url, data=data, headers=headers, method=method)",
        "        try:",
        "            with self._opener(request, timeout=self._timeout) as response:",
        "                status, raw = response.status, response.read()",
        "        except urllib.error.HTTPError as error:",
        "            status, raw = error.code, error.read()",
        "        if status == 204:",
        "            return None",
        "        try:",
        "            parsed = json.loads(raw) if raw else None",
        "        except ValueError:",
        "            parsed = None",
        "        if status >= 400:",
        "            err = parsed.get('error') if isinstance(parsed, dict) else None",
        "            err = err if isinstance(err, dict) else {}",
        "            raise OrchivioApiError(status, err.get('code') or 'http_error', err.get('message') or f'Request failed ({status})', err.get('details'))",
        "        return parsed",
        "",
    ]))
    return "\n".join(out) + "\n"


__all__ = ["build_python_client", "py_type", "snake"]
