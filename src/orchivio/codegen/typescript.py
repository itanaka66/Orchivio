"""A typed TypeScript client for the data API of an application (FR-031, docs/CLIENTS.md).

Generated from the same OpenAPI document that ``tests/integration/test_openapi.py`` checks against real responses, so the client can
only offer operations the runtime implements for at least one role, with the field types, required fields, enumerations and
filters the model defines. The output is a single dependency-free file (``fetch`` only), deterministic for a given model, and carries
the model hash so a stale client can be recognised.

Not generated: flow runs and process starts (they are not part of the data API's OpenAPI document), pages, and authentication
(the caller supplies headers or cookies through ``OrchivioClientOptions``).
"""

from __future__ import annotations

import re
from typing import Any

from orchivio.model import AppModel, model_hash

from .openapi import build_openapi

_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _prop(name: str) -> str:
    return name if _IDENT.match(name) else f"'{name}'"


def _lit(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


def ts_type(schema: dict[str, Any]) -> str:
    """The TypeScript type of a JSON-Schema fragment as produced by ``build_openapi``."""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(_lit(v) for v in schema["enum"])
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(sorted({ts_type({**schema, "type": x}) for x in t}, key=lambda s: (s == "null", s)))
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        inner = ts_type(schema.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if t == "object":
        props = schema.get("properties")
        if not props:
            return "Record<string, unknown>"
        req = set(schema.get("required", []))
        return "{ " + "; ".join(f"{'readonly ' if p.get('readOnly') else ''}{_prop(k)}{'' if k in req else '?'}: {ts_type(p)}" for k, p in props.items()) + " }"
    return "unknown"


def _doc(schema: dict[str, Any]) -> str:
    bits = []
    if schema.get("format") in ("uuid", "date", "date-time"):
        bits.append(str(schema["format"]))
    if schema.get("maxLength"):
        bits.append(f"max {schema['maxLength']} characters")
    if "minimum" in schema:
        bits.append(f"min {schema['minimum']}")
    if "maximum" in schema:
        bits.append(f"max {schema['maximum']}")
    if schema.get("x-orchivio-computed"):
        bits.append(f"computed ({schema['x-orchivio-computed']})")
    if schema.get("description"):
        bits.append(str(schema["description"]).replace("*/", "* /"))
    return f"  /** {'; '.join(bits)} */\n" if bits else ""


def _interface(name: str, schema: dict[str, Any]) -> str:
    req = set(schema.get("required", []))
    lines = []
    for key, p in schema.get("properties", {}).items():
        lines.append(f"{_doc(p)}  {'readonly ' if p.get('readOnly') else ''}{_prop(key)}{'' if key in req else '?'}: {ts_type(p)}")
    return f"export interface {name} {{\n" + "\n".join(lines) + "\n}\n"


def _referenced(node: Any, schemas: dict[str, Any]) -> set[str]:
    """Names of the schemas reachable from ``node`` through ``$ref``s."""
    found: set[str] = set()

    def walk(n: Any) -> None:
        if isinstance(n, dict):
            ref = n.get("$ref")
            if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
                name = ref.rsplit("/", 1)[-1]
                if name not in found:
                    found.add(name)
                    walk(schemas.get(name, {}))
            for v in n.values():
                walk(v)
        elif isinstance(n, list):
            for v in n:
                walk(v)

    walk(node)
    return found


def build_client(model: AppModel) -> str:
    doc = build_openapi(model)
    schemas: dict[str, Any] = doc["components"]["schemas"]
    out = [
        f"// Generated by Orchivio from the model of \"{model.application.key}\" ({model_hash(model)}). Do not edit; regenerate it.\n"
        "// Only operations that at least one role may perform are included. Which roles may do what is up to the server.\n",
        "export interface OrchivioPage<T> { items: T[]; total: number; limit: number; offset: number }\n",
        "export class OrchivioApiError extends Error {\n"
        "  constructor(readonly status: number, readonly code: string, message: string, readonly details?: unknown) {\n"
        "    super(message)\n    this.name = 'OrchivioApiError'\n  }\n}\n",
        "export interface OrchivioClientOptions {\n"
        "  /** Where the data API lives, without a trailing slash, e.g. `/api/v1/applications/<id>/preview`. */\n  baseUrl: string\n"
        "  /** Extra headers per request (an access token, `X-Preview-User`, ...). */\n  headers?: () => Record<string, string> | Promise<Record<string, string>>\n"
        "  fetch?: typeof fetch\n  credentials?: RequestCredentials\n}\n",
    ]
    used = _referenced(doc["paths"], schemas)
    for name, schema in schemas.items():
        props = schema.get("properties", {})
        if name not in used or name == "Error" or {"items", "total", "limit", "offset"} <= set(props):
            continue  # unused schemas, and the error and page envelopes the helpers above already express
        out.append(_interface(name, schema))

    entities: dict[str, dict[str, Any]] = {}
    for path, ops in doc["paths"].items():
        entity = path.split("/")[2]
        for verb, op in ops.items():
            entities.setdefault(entity, {})[op["operationId"].split("_", 1)[0]] = (path, verb, op)

    list_types, groups = [], []
    for ops in entities.values():
        read_ref = next(iter(ops.values()))[2]["tags"][0]
        schema_name = next((ts_type(o[2]["responses"]["200"]["content"]["application/json"]["schema"]) for k, o in ops.items() if k == "read"), None) \
            or ts_type(ops["list"][2]["responses"]["200"]["content"]["application/json"]["schema"]).removesuffix("Page")
        lines = []
        if "list" in ops:
            params = {p["name"]: p for p in ops["list"][2].get("parameters", []) if "name" in p}
            order = ts_type(params["order_by"]["schema"]) if "order_by" in params else "string"
            filt = "".join(f"\n    {_prop(n[2:])}?: {ts_type(p['schema'])}" for n, p in params.items() if n.startswith("f."))
            pname = f"{schema_name}ListParams"
            list_types.append(f"export interface {pname} {{\n  limit?: number\n  offset?: number\n  orderBy?: {order}\n  desc?: boolean\n  /** Equality filters on stored fields. */\n  filter?: {{{filt}\n  }}\n}}\n")
            lines.append(f"    list: (params: {pname} = {{}}) => this.request<OrchivioPage<{schema_name}>>('GET', '{ops['list'][0]}', {{ query: listQuery(params) }}),")
        if "create" in ops:
            body = ts_type(ops["create"][2]["requestBody"]["content"]["application/json"]["schema"])
            lines.append(f"    create: (body: {body}) => this.request<{schema_name}>('POST', '{ops['create'][0]}', {{ body }}),")
        if "read" in ops:
            lines.append(f"    get: (id: string) => this.request<{schema_name}>('GET', '{ops['read'][0]}'.replace('{{id}}', encodeURIComponent(id))),")
        if "update" in ops:
            body = ts_type(ops["update"][2]["requestBody"]["content"]["application/json"]["schema"])
            lines.append(f"    update: (id: string, patch: {body}) => this.request<{schema_name}>('PATCH', '{ops['update'][0]}'.replace('{{id}}', encodeURIComponent(id)), {{ body: patch }}),")
        if "delete" in ops:
            lines.append(f"    delete: (id: string) => this.request<void>('DELETE', '{ops['delete'][0]}'.replace('{{id}}', encodeURIComponent(id))),")
        member = schema_name[:1].lower() + schema_name[1:]
        groups.append(f"  /** {read_ref} */\n  readonly {member} = {{\n" + "\n".join(lines) + "\n  }\n")

    out.extend(list_types)
    out.append("function listQuery(p: { limit?: number; offset?: number; orderBy?: string; desc?: boolean; filter?: Record<string, unknown> }): Record<string, string> {\n"
               "  const q: Record<string, string> = {}\n"
               "  if (p.limit !== undefined) q.limit = String(p.limit)\n"
               "  if (p.offset !== undefined) q.offset = String(p.offset)\n"
               "  if (p.orderBy) q.order_by = p.orderBy\n"
               "  if (p.desc) q.desc = 'true'\n"
               "  for (const [k, v] of Object.entries(p.filter ?? {})) if (v !== undefined && v !== null) q[`f.${k}`] = String(v)\n"
               "  return q\n}\n")
    out.append(
        "export class OrchivioDataClient {\n"
        "  constructor(private readonly options: OrchivioClientOptions) {}\n\n"
        "  private async request<T>(method: string, path: string, init: { query?: Record<string, string>; body?: unknown } = {}): Promise<T> {\n"
        "    const qs = init.query && Object.keys(init.query).length ? `?${new URLSearchParams(init.query).toString()}` : ''\n"
        "    const headers: Record<string, string> = { Accept: 'application/json', ...(await this.options.headers?.()) }\n"
        "    if (init.body !== undefined) headers['Content-Type'] = 'application/json'\n"
        "    const res = await (this.options.fetch ?? fetch)(`${this.options.baseUrl}${path}${qs}`, {\n"
        "      method, headers, credentials: this.options.credentials, body: init.body === undefined ? undefined : JSON.stringify(init.body),\n"
        "    })\n"
        "    if (res.status === 204) return undefined as T\n"
        "    const text = await res.text()\n"
        "    let data: unknown\n"
        "    try { data = text ? JSON.parse(text) : undefined } catch { /* not JSON */ }\n"
        "    if (!res.ok) {\n"
        "      const e = (data as { error?: { code?: string; message?: string; details?: unknown } } | undefined)?.error\n"
        "      throw new OrchivioApiError(res.status, e?.code ?? 'http_error', e?.message ?? `Request failed (${res.status})`, e?.details)\n"
        "    }\n"
        "    return data as T\n"
        "  }\n\n" + "\n".join(groups) + "}\n")
    return "\n".join(out)


__all__ = ["build_client", "ts_type"]
